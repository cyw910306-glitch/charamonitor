"""Writes Sources/DogMonitor/Sprite/Originals<Name>.swift (OriginalCharacterSet2 art) from tancat.py.
Run from this folder: python3 emit.py ../..   Previews: OUT=../../qa/originals python3 render.py tancat"""
import json, importlib, sys
from lib import *
PKG = sys.argv[1]
CHARS = [("tancat", "TanCat", "tanCat")]
for mod, Name, prop in CHARS:
    m = importlib.import_module(mod)
    validate(mod, m.data, getattr(m, "HOP_OK", ()))
    d = m.data
    lines = ["{", '"palette": ' + json.dumps(d["palette"], sort_keys=True) + ","]
    for section in ("poses", "extras"):
        keys = POSES if section == "poses" else EXTRAS
        lines.append(f'"{section}": {{')
        for ki, k in enumerate(keys):
            frs = d[section][k]
            lines.append(f'"{k}": [')
            for fi, fr in enumerate(frs):
                rows = ",\n".join('"' + r + '"' for r in fr)
                lines.append("[\n" + rows + "\n]" + ("," if fi < len(frs) - 1 else ""))
            lines.append("]" + ("," if ki < len(keys) - 1 else ""))
        lines.append("}" + ("," if section == "poses" else ""))
    lines.append("}")
    body = "\n".join(lines)
    json.loads(body)
    src = f"""// Generated by tools/originals-set2/emit.py from tools/originals-set2/{mod}.py. Edit the generator, not this file.
// frames.json format (FrameArt): palette + 20 rows x 34 characters per frame, plus "extras" (hungry, eat, special).

extension OriginalArt {{
    public static let {prop} = #\"\"\"
{body}
\"\"\"#
}}
"""
    open(f"{PKG}/Sources/CharaCore/Originals{Name}.swift", "w").write(src)
    print(Name, len(src))
