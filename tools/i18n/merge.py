#!/usr/bin/env python3
"""Merges the translators' chunk-N.en.json files into Resources/en.lproj/Localizable.strings.

Input (tools/i18n/): strings.json from extract.py, and chunk-1.en.json .. chunk-3.en.json, each [{key, en}].
Output: Resources/en.lproj/Localizable.strings ("Korean key" = "English";), which scripts/build_app.sh and
build_mas.sh copy into the app. Reports keys with no English (they show in Korean), keys no longer in the
source, and English whose format arguments do not match the key.

Format rules (what the app looks up, checked here):
- A key with arguments (%@, %lld, %d, %lf ...) is formatted: the English needs the same arguments, may
  reorder them as %1$@ %2$lld, may drop trailing ones (%@%@ 생각 중이에요 -> "%1$@ is thinking"), and writes
  a literal percent as %%.
- A key without arguments is used as is: a literal percent stays a single % ("CPU 5% 미만" -> "CPU under 5%").

Usage: python3 tools/i18n/merge.py [--strict]   (--strict: exit 1 when any key has no English)
       python3 tools/i18n/merge.py --self-test
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = ROOT / "tools" / "i18n"
OUT = ROOT / "Resources" / "en.lproj" / "Localizable.strings"
CHUNKS = 3
SPEC = re.compile(r"%(?:(\d+)\$)?[-+ #0]*\d*(?:\.\d+)?(hh|h|ll|l|q|z|t|j)?([@dDiuUxXoOfFeEgGcCsSpaA%])")


def specs(text):
    """The arguments a format string takes, as {position: conversion}, or None when a % is malformed."""
    out, nxt, pos = {}, 1, 0
    while True:
        i = text.find("%", pos)
        if i < 0:
            return out
        m = SPEC.match(text, i)
        if not m:
            return None
        pos = m.end()
        if m.group(3) == "%":
            continue
        n = int(m.group(1)) if m.group(1) else nxt
        nxt = n + 1
        out[n] = (m.group(2) or "") + m.group(3)


def check(key, en):
    """Why this English would misbehave, or None."""
    want = specs(key)
    if not want:  # no arguments: the text is shown verbatim
        return None
    got = specs(en)
    if got is None:
        return "a % that is not an argument (write a literal percent as %%)"
    for n, conv in got.items():
        if want.get(n) != conv:
            return f"argument {n} is %{conv}, the key has %{want.get(n, 'nothing')}"
    if sorted(got) != list(range(1, len(got) + 1)):  # only trailing arguments may be left out
        return "leaves out an argument before one it uses"
    return None


def escape(s):
    return (s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")
            .replace("\r", "\\r"))


def self_test():
    assert check("CPU 5% 미만", "CPU under 5%") is None
    assert check("%lld개", "%lld items") is None
    assert check("%@%@ 생각 중이에요", "%1$@ is thinking") is None
    assert check("%@ · %lld", "%2$lld · %1$@") is None
    assert check("%@ · %lld", "%2$lld") is not None
    assert check("%lld개", "%@ items") is not None
    assert check("%lld%% 할인", "%lld% off") is not None  # "% o" would read an octal argument
    assert check("%lld%% 할인", "%lld%% off") is None
    assert escape('a"b\\c\nd') == 'a\\"b\\\\c\\nd'
    print("ok")


def main():
    if "--self-test" in sys.argv:
        return self_test()
    rows = json.loads((HERE / "strings.json").read_text())
    keys = {r["key"]: r for r in rows}
    english, problems, stale = {}, [], []
    for k in range(1, CHUNKS + 1):
        path = HERE / f"chunk-{k}.en.json"
        if not path.exists():
            print(f"missing file: {path.name}")
            continue
        for item in json.loads(path.read_text()):
            key, en = item.get("key"), (item.get("en") or "")
            if key not in keys:
                stale.append(key)
                continue
            if not en.strip():
                continue
            why = check(key, en)
            if why:
                problems.append(f"{keys[key]['file']}:{keys[key]['line']}: {key!r} -> {en!r}: {why}")
                continue
            english[key] = en

    lines = ["/* English UI. Generated by tools/i18n/merge.py from chunk-N.en.json; do not edit by hand. */", ""]
    for r in rows:
        if r["key"] in english:
            lines.append(f"/* {r['file']}:{r['line']} */")
            lines.append(f'"{escape(r["key"])}" = "{escape(english[r["key"]])}";')
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")

    # Read it back the way Foundation does, so an escaping slip never ships.
    parsed = json.loads(subprocess.run(["plutil", "-convert", "json", "-o", "-", str(OUT)],
                                       capture_output=True, text=True, check=True).stdout)
    assert parsed == english, "Localizable.strings does not read back as written"

    missing = [r for r in rows if r["key"] not in english and not any(r["key"] in p for p in problems)]
    print(f"{OUT.relative_to(ROOT)}: {len(english)} / {len(rows)} keys in English")
    for p in problems:
        print(f"format mismatch: {p}")
    for r in missing:
        print(f"no English: {r['file']}:{r['line']}: {r['key']!r}")
    for key in stale:
        print(f"not in the source any more: {key!r}")
    print(f"missing {len(missing)}, format mismatches {len(problems)}, stale {len(stale)}")
    if problems or ("--strict" in sys.argv and missing):
        sys.exit(1)


if __name__ == "__main__":
    main()
